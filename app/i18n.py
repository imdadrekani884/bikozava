def normalize_lang(lang: str, fallback: str = "ku") -> str:
    code = (lang or "").strip().lower()
    if code in SUPPORTED_LANGUAGES:
        return code
    return fallback if fallback in SUPPORTED_LANGUAGES else "ku"


def get_ui_strings(lang: str) -> Dict[str, str]:
    code = normalize_lang(lang)
    return UI_STRINGS[code]


def localize_field(record: Dict[str, Any], base_key: str, lang: str) -> str:
    code = normalize_lang(lang)
    primary = (record.get(f"{base_key}_{code}") or "").strip()
    if primary:
        return primary
    for fb in ("ku", "en", "ar"):
        val = (record.get(f"{base_key}_{fb}") or "").strip()
        if val:
            return val
    return ""
